// i18n.js — the portal's language. app.js writes its text in Japanese and
// wraps it in T(); with English on, T looks the text up in EN (keep the
// keys identical to the strings in app.js — TestPortalStringsTranslated
// fails on a T() string missing here). The language is the per-user pref
// "lang" (/api/prefs; "" = follow the browser), read from the copy app.js
// keeps in localStorage so the first paint is already right.
"use strict";
const LANG = (() => {
  let p = "";
  try { p = JSON.parse(localStorage.getItem("ccdash.look") || "{}").lang || ""; } catch {}
  if (p === "ja" || p === "en") return p;
  return /^ja\b/i.test(navigator.language || "") ? "ja" : "en";
})();
document.documentElement.lang = LANG;

// T translates s and fills {0}, {1} … with args.
function T(s, ...args) {
  if (LANG === "en" && Object.hasOwn(EN, s)) s = EN[s];
  return args.length ? s.replace(/\{(\d+)\}/g, (_, i) => String(args[+i] ?? "")) : s;
}

// tr translates text a collector sends, which is Japanese whatever the
// viewer's language (the wire format is shared with the TUI and the
// Android app): an exact label, or "label: detail" (e.g. 回答待ち: <note>).
function tr(s) {
  if (LANG !== "en" || !s) return s || "";
  if (Object.hasOwn(EN, s)) return EN[s];
  const i = s.indexOf(": ");
  if (i > 0 && Object.hasOwn(EN, s.slice(0, i))) return EN[s.slice(0, i)] + s.slice(i);
  return s;
}

const WEEKDAY_EN = { 月: "Mon", 火: "Tue", 水: "Wed", 木: "Thu", 金: "Fri", 土: "Sat", 日: "Sun" };

// trHeading translates a task bucket heading, e.g. 来週（10/27 月〜10/31 金）.
function trHeading(s) {
  if (LANG !== "en" || !s) return s || "";
  return s.replace(/^[^（]+/, (m) => tr(m)).replace(/（/g, " (").replace(/）/g, ")")
    .replace(/ ([月火水木金土日])/g, (_, d) => " " + WEEKDAY_EN[d]).replace(/〜/g, " – ");
}

// trTimeline translates the timeline entries ccdash itself writes on a
// status or plan change; anything else (a person's or Claude's note) stays.
function trTimeline(s) {
  if (LANG !== "en" || !s) return s || "";
  const m = /^(状態|やる日)を「(.*?)」から「(.*?)」に(自動で)?変更(?:（(.*)）)?$/.exec(s);
  if (!m) return s;
  return `${m[1] === "状態" ? "Status" : "Plan"} changed${m[4] ? " automatically" : ""} from "${tr(m[2])}" to "${tr(m[3])}"` + (m[5] ? ` (${m[5]})` : "");
}

